//! End-to-end export tests that actually run the `duckdb` CLI over a Parquet
//! fixture, asserting the real ndjson output (shape + id-dedup + latest/history
//! window semantics). These exercise the exact SQL the HTTP endpoint and CLI run.
//!
//! The test **skips** when no duckdb is available, so a machine without one still
//! passes, unless `NOZZL_REQUIRE_DUCKDB=1`, which CI's test step sets after installing
//! duckdb: there a missing duckdb fails the tests instead of skipping them without a
//! word. Point it at a specific binary with
//! `DUCKDB_BIN=/path/to/duckdb cargo test -p nozzl-export --test export_duckdb`.
//!
//! Fixtures are generated by duckdb itself (the test already requires duckdb), so
//! there is no committed binary blob to rot against schema changes and no need to
//! widen `nozzl-archive`'s API. Real-event signature round-trip is covered by the
//! local acceptance run over `./data/events`.

use std::path::{Path, PathBuf};

use futures_util::StreamExt;
use nozzl_export::{ExportMode, ExportParams, spawn_export};

/// Resolve a duckdb binary: `$DUCKDB_BIN`, else `duckdb` on PATH, else
/// `~/.local/bin/duckdb`. Returns None (-> skip) if none runs `--version`, and
/// panics instead when `NOZZL_REQUIRE_DUCKDB=1` (see the module docs).
fn duckdb_bin() -> Option<PathBuf> {
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Ok(p) = std::env::var("DUCKDB_BIN") {
        candidates.push(PathBuf::from(p));
    }
    candidates.push(PathBuf::from("duckdb"));
    if let Ok(home) = std::env::var("HOME") {
        candidates.push(PathBuf::from(home).join(".local/bin/duckdb"));
    }
    let found = candidates.into_iter().find(|bin| {
        std::process::Command::new(bin)
            .arg("--version")
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    });
    if found.is_none() && std::env::var_os("NOZZL_REQUIRE_DUCKDB").is_some_and(|v| v == "1") {
        panic!(
            "no duckdb found, and NOZZL_REQUIRE_DUCKDB=1 says one must run \
             (CI sets it after installing duckdb, .github/workflows/ci.yml)"
        );
    }
    found
}

/// A 64-hex id/pubkey derived from a short seed (padded with 'f').
fn hex64(seed: &str) -> String {
    format!("{seed:f<64}")
}
/// A 128-hex signature from a seed.
fn hex128(seed: &str) -> String {
    format!("{seed:f<128}")
}

/// One archived event row for the fixture.
struct Row {
    id: String,
    pubkey: String,
    kind: u16,
    created_at: i64,
    tags_sql: &'static str,
    d_tag: Option<&'static str>,
    ingested_at: i64,
}

/// Write `rows` as a Parquet chunk at the real archive layout
/// `{root}/c={class}/k={kind}/p=0/dt=2026-01-01/events-{n}.parquet` using duckdb,
/// so the export's `read_parquet` sees genuine Parquet with the
/// `tags: LIST(LIST(VARCHAR))` / nullable `d_tag` shape. `class` is the bare class
/// name (`replaceable`); the Hive `c=` prefix is applied here.
fn write_chunk(duckdb: &Path, root: &Path, class: &str, kind: u16, n: u32, rows: &[Row]) {
    let dir = root
        .join(format!("c={class}"))
        .join(format!("k={kind}"))
        .join("p=0")
        .join("dt=2026-01-01");
    std::fs::create_dir_all(&dir).unwrap();
    let out = dir.join(format!("events-{n}.parquet"));

    let values: Vec<String> = rows
        .iter()
        .map(|r| {
            let d = match r.d_tag {
                Some(s) => format!("'{s}'"),
                None => "CAST(NULL AS VARCHAR)".to_string(),
            };
            format!(
                "('{}','{}',CAST({} AS INTEGER),CAST({} AS BIGINT),'',{},'{}',{},CAST({} AS BIGINT))",
                r.id, r.pubkey, r.kind, r.created_at, r.tags_sql, hex128("sig"), d, r.ingested_at
            )
        })
        .collect();

    let select = format!(
        "SELECT * FROM (VALUES {}) t(id,pubkey,kind,created_at,content,tags,sig,d_tag,ingested_at)",
        values.join(",")
    );
    let sql = format!("COPY ({select}) TO '{}' (FORMAT PARQUET)", out.display());
    let status = std::process::Command::new(duckdb)
        .arg("-c")
        .arg(sql)
        .status()
        .unwrap();
    assert!(status.success(), "duckdb fixture write failed");
}

async fn export_lines(
    root: &Path,
    kind: u16,
    mode: ExportMode,
    duckdb: &Path,
) -> Vec<serde_json::Value> {
    let mut stream = spawn_export(
        ExportParams {
            archive_root: root.to_path_buf(),
            kind,
            mode,
            duckdb_bin: duckdb.to_path_buf(),
        },
        None,
    )
    .expect("spawn_export");

    let mut buf = Vec::new();
    while let Some(chunk) = stream.next().await {
        buf.extend_from_slice(&chunk.expect("stream chunk"));
    }
    String::from_utf8(buf)
        .unwrap()
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            serde_json::from_str::<serde_json::Value>(l).expect("each line is one JSON object")
        })
        .collect()
}

/// Every line is a bare NIP-01 object: exactly the 7 wire fields, `tags` nested,
/// `kind`/`created_at` numbers — no `d_tag`/`ingested_at` leak.
fn assert_nip01_shape(lines: &[serde_json::Value]) {
    for o in lines {
        let obj = o.as_object().unwrap();
        let mut keys: Vec<&String> = obj.keys().collect();
        keys.sort();
        assert_eq!(
            keys,
            vec![
                "content",
                "created_at",
                "id",
                "kind",
                "pubkey",
                "sig",
                "tags"
            ],
            "bare NIP-01 fields only (no d_tag/ingested_at): {o}"
        );
        assert!(obj["kind"].is_number());
        assert!(obj["created_at"].is_number());
        let tags = obj["tags"].as_array().unwrap();
        for t in tags {
            assert!(t.is_array(), "each tag is an array: {o}");
        }
    }
}

#[tokio::test]
async fn replaceable_latest_vs_history_and_id_dedup() {
    let Some(duckdb) = duckdb_bin() else {
        eprintln!("skipping: no duckdb available");
        return;
    };
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path();
    let pk_a = hex64("aa");
    let pk_b = hex64("bb");

    // Chunk 1: A has two versions (created_at 100, 200); B has one (50).
    write_chunk(
        &duckdb,
        root,
        "replaceable",
        0,
        1,
        &[
            Row {
                id: hex64("a1"),
                pubkey: pk_a.clone(),
                kind: 0,
                created_at: 100,
                tags_sql: "[['r','wss://a/']]",
                d_tag: None,
                ingested_at: 10,
            },
            Row {
                id: hex64("a2"),
                pubkey: pk_a.clone(),
                kind: 0,
                created_at: 200,
                tags_sql: "[['r','wss://b/','read']]",
                d_tag: None,
                ingested_at: 20,
            },
            Row {
                id: hex64("b1"),
                pubkey: pk_b.clone(),
                kind: 0,
                created_at: 50,
                tags_sql: "[['r','wss://c/']]",
                d_tag: None,
                ingested_at: 15,
            },
        ],
    );
    // Chunk 2: a duplicate of id a2 seen again later (id-level dedup must collapse it).
    write_chunk(
        &duckdb,
        root,
        "replaceable",
        0,
        2,
        &[Row {
            id: hex64("a2"),
            pubkey: pk_a.clone(),
            kind: 0,
            created_at: 200,
            tags_sql: "[['r','wss://b/','read']]",
            d_tag: None,
            ingested_at: 99,
        }],
    );

    // history: id-dedup over 4 rows → 3 distinct ids (a1, a2, b1).
    let history = export_lines(root, 0, ExportMode::History, &duckdb).await;
    assert_nip01_shape(&history);
    assert_eq!(history.len(), 3, "history keeps all distinct versions");

    // latest: one per (kind,pubkey) → A's newest (a2@200) + B (b1@50).
    let latest = export_lines(root, 0, ExportMode::Latest, &duckdb).await;
    assert_nip01_shape(&latest);
    assert_eq!(latest.len(), 2, "latest collapses to one per coordinate");
    let ids: std::collections::HashSet<String> = latest
        .iter()
        .map(|o| o["id"].as_str().unwrap().to_string())
        .collect();
    assert!(ids.contains(&hex64("a2")), "A's newest version wins");
    assert!(!ids.contains(&hex64("a1")), "A's older version is dropped");
    assert!(ids.contains(&hex64("b1")));
}

#[tokio::test]
async fn addressable_latest_groups_null_d_tag_separately() {
    let Some(duckdb) = duckdb_bin() else {
        eprintln!("skipping: no duckdb available");
        return;
    };
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path();
    let pk = hex64("cc");

    write_chunk(
        &duckdb,
        root,
        "addressable",
        30000,
        1,
        &[
            // coordinate (pk, d="x"): two versions
            Row {
                id: hex64("d1"),
                pubkey: pk.clone(),
                kind: 30000,
                created_at: 100,
                tags_sql: "[['d','x']]",
                d_tag: Some("x"),
                ingested_at: 10,
            },
            Row {
                id: hex64("d2"),
                pubkey: pk.clone(),
                kind: 30000,
                created_at: 200,
                tags_sql: "[['d','x']]",
                d_tag: Some("x"),
                ingested_at: 20,
            },
            // coordinate (pk, d=NULL): addressable event without a d tag
            Row {
                id: hex64("d3"),
                pubkey: pk.clone(),
                kind: 30000,
                created_at: 150,
                tags_sql: "[['t','misc']]",
                d_tag: None,
                ingested_at: 15,
            },
        ],
    );

    let latest = export_lines(root, 30000, ExportMode::Latest, &duckdb).await;
    assert_nip01_shape(&latest);
    // (pk,"x") collapses to d2@200; (pk,NULL) is its own coordinate → 2 rows.
    assert_eq!(latest.len(), 2, "NULL d_tag is a distinct coordinate");
    let ids: std::collections::HashSet<String> = latest
        .iter()
        .map(|o| o["id"].as_str().unwrap().to_string())
        .collect();
    assert!(ids.contains(&hex64("d2")));
    assert!(ids.contains(&hex64("d3")));
    assert!(!ids.contains(&hex64("d1")));
}

#[tokio::test]
async fn regular_kind_ignores_mode() {
    let Some(duckdb) = duckdb_bin() else {
        eprintln!("skipping: no duckdb available");
        return;
    };
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path();
    let pk = hex64("ee");

    write_chunk(
        &duckdb,
        root,
        "regular",
        9735,
        1,
        &[
            Row {
                id: hex64("f1"),
                pubkey: pk.clone(),
                kind: 9735,
                created_at: 100,
                tags_sql: "[['p','abc']]",
                d_tag: None,
                ingested_at: 10,
            },
            Row {
                id: hex64("f2"),
                pubkey: pk.clone(),
                kind: 9735,
                created_at: 200,
                tags_sql: "[['p','def']]",
                d_tag: None,
                ingested_at: 20,
            },
        ],
    );

    let latest = export_lines(root, 9735, ExportMode::Latest, &duckdb).await;
    let history = export_lines(root, 9735, ExportMode::History, &duckdb).await;
    assert_nip01_shape(&latest);
    assert_eq!(latest.len(), 2, "regular keeps every event");
    assert_eq!(
        latest.len(),
        history.len(),
        "mode is ignored for regular kinds"
    );
}
